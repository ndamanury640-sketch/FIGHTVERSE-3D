CREATE DATABASE IF NOT EXISTS fightverse_db CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE fightverse_db;
CREATE TABLE IF NOT EXISTS users (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 username VARCHAR(24) NOT NULL UNIQUE,
 email VARCHAR(190) NOT NULL UNIQUE,
 password_hash VARCHAR(255) NOT NULL,
 role ENUM('player','admin') NOT NULL DEFAULT 'player',
 status ENUM('active','disabled') NOT NULL DEFAULT 'active',
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 last_login DATETIME NULL
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS characters (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 slug VARCHAR(64) NOT NULL UNIQUE,
 name VARCHAR(80) NOT NULL,
 description VARCHAR(255) NOT NULL DEFAULT '',
 portrait_path VARCHAR(255) NOT NULL,
 sprite_path VARCHAR(255) NOT NULL,
 base_hp SMALLINT UNSIGNED NOT NULL DEFAULT 100,
 attack_power SMALLINT UNSIGNED NOT NULL DEFAULT 10,
 defense SMALLINT UNSIGNED NOT NULL DEFAULT 5,
 movement_speed DECIMAL(5,2) NOT NULL DEFAULT 3.50,
 special_ability VARCHAR(100) NOT NULL DEFAULT 'Special Attack',
 is_active TINYINT(1) NOT NULL DEFAULT 1
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS player_profiles (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 user_id BIGINT UNSIGNED NOT NULL UNIQUE,
 display_name VARCHAR(50) NOT NULL,
 favorite_character_id INT UNSIGNED NULL,
 avatar VARCHAR(255) NULL,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 CONSTRAINT fk_profile_user FOREIGN KEY(user_id) REFERENCES users(id) ON DELETE CASCADE,
 CONSTRAINT fk_profile_character FOREIGN KEY(favorite_character_id) REFERENCES characters(id) ON DELETE SET NULL
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS matches (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 player_id BIGINT UNSIGNED NOT NULL,
 player_character_id INT UNSIGNED NOT NULL,
 opponent_character_id INT UNSIGNED NOT NULL,
 game_mode ENUM('versus','training','online','ranked') NOT NULL DEFAULT 'versus',
 difficulty ENUM('easy','normal','hard') NOT NULL DEFAULT 'normal',
 result ENUM('win','loss','draw') NOT NULL,
 duration_seconds SMALLINT UNSIGNED NOT NULL DEFAULT 0,
 damage_dealt INT UNSIGNED NOT NULL DEFAULT 0,
 successful_hits SMALLINT UNSIGNED NOT NULL DEFAULT 0,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 INDEX idx_matches_player_created(player_id,created_at),
 INDEX idx_matches_result(result),
 CONSTRAINT fk_match_player FOREIGN KEY(player_id) REFERENCES users(id) ON DELETE CASCADE,
 CONSTRAINT fk_match_character FOREIGN KEY(player_character_id) REFERENCES characters(id),
 CONSTRAINT fk_match_opponent FOREIGN KEY(opponent_character_id) REFERENCES characters(id)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS player_statistics (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 user_id BIGINT UNSIGNED NOT NULL UNIQUE,
 total_matches INT UNSIGNED NOT NULL DEFAULT 0,
 wins INT UNSIGNED NOT NULL DEFAULT 0,
 losses INT UNSIGNED NOT NULL DEFAULT 0,
 draws INT UNSIGNED NOT NULL DEFAULT 0,
 total_damage BIGINT UNSIGNED NOT NULL DEFAULT 0,
 updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 CONSTRAINT fk_stats_user FOREIGN KEY(user_id) REFERENCES users(id) ON DELETE CASCADE
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS admin_audit_log (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 admin_user_id BIGINT UNSIGNED NOT NULL,
 action VARCHAR(100) NOT NULL,
 target_type VARCHAR(60) NOT NULL,
 target_id BIGINT NULL,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 INDEX idx_audit_created(created_at),
 CONSTRAINT fk_audit_admin FOREIGN KEY(admin_user_id) REFERENCES users(id)
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS player_ratings (
 user_id BIGINT UNSIGNED PRIMARY KEY,
 elo SMALLINT UNSIGNED NOT NULL DEFAULT 1000,
 peak_elo SMALLINT UNSIGNED NOT NULL DEFAULT 1000,
 games INT UNSIGNED NOT NULL DEFAULT 0,
 wins INT UNSIGNED NOT NULL DEFAULT 0,
 losses INT UNSIGNED NOT NULL DEFAULT 0,
 draws INT UNSIGNED NOT NULL DEFAULT 0,
 updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 INDEX idx_rating_elo(elo),
 CONSTRAINT fk_rating_user FOREIGN KEY(user_id) REFERENCES users(id) ON DELETE CASCADE
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS online_matches (
 match_id VARCHAR(32) PRIMARY KEY,
 ranked TINYINT(1) NOT NULL DEFAULT 0,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB;
